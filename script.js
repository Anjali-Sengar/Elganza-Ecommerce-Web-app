const urlParams = new URLSearchParams(window.location.search);
const id = urlParams.get("id");

const product =
{
    id: id,
    ...products[id]
}

let quantity = 1;

const productName = document.getElementById("productName");
const productPrice = document.getElementById("productPrice");
const productImage = document.getElementById("productImage");
const productDescription = document.getElementById("productDescription");

if (productName) {
    productName.textContent = product.name;
    productPrice.textContent = "₹" + product.price;
    productImage.src = product.image;
    productDescription.textContent = product.description;
}

const addToCart = document.getElementById("addToCart");

if (addToCart) {

    addToCart.addEventListener("click", function () {
        let cart = JSON.parse(localStorage.getItem("cart")) || [];

        let alreadyInCart = cart.find(function (item) {
            return item.id === product.id;
        });

        if (alreadyInCart) {
            alert("Product already added to cart!");
        }
        else {
            cart.push({
                id: id,
                ...product
            });
            localStorage.setItem("cart", JSON.stringify(cart));
            
        }


    });
}


const cartContainer = document.getElementById("cart_html");

if (cartContainer) {

    let cart = JSON.parse(localStorage.getItem("cart")) || [];

    cart.forEach(function (product) {
        cartContainer.innerHTML +=
            `<div class="cart_item"> 
       <div class="cart_image" style="background-image: url('${product.image}')"></div>
    <div class="cart_data">
        <h2> ${product.name} </h2>
        <h3>₹${product.price}</h3>
        <p>${product.description}</p>
          <div class="quantity-box">
        <button class="minus" data-id="${product.id}">-</button>
        <span>1</span>
        <button class="plus" data-id="${product.id}">+</button>
</div>
   <button class="remove-btn" data-id="${product.id}">Remove</button>


        </div>

        `;
    });
}

document.addEventListener("click", (e) => {
    if(e.target.classList.contains("plus")){
        let span= e.target.parentElement.querySelector("span");
        span.innerText = Number(span.innerText) + 1;
    }

     if(e.target.classList.contains("minus")){
        let span= e.target.parentElement.querySelector("span");
        if(Number(span.innerText > 1)){
            span.innerText = Number(span.innerText) - 1;
        }
    }
});


document.addEventListener("click", function (e) {
    if (e.target.classList.contains("remove-btn")) {
        const id = e.target.dataset.id;
        let cart = JSON.parse(localStorage.getItem("cart")) || [];

        cart = cart.filter(function (product) {
            return product.id !== id;
        });

        localStorage.setItem("cart", JSON.stringify(cart));
        this.location.reload();

    }
});
